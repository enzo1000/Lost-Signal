using UnityEngine;

public class GameFlowManager : MonoBehaviour
{
    //================================================================================================================================
    //================================================================================================================================
    public enum GameGoal {
        FirstGoal,
        SecondGoal,
        ThirdGoal,
        NoGoal
    }

    //================================================================================================================================
    //================================================================================================================================
    public enum GamePhase {
        FirstPhase,
        SecondPhase,
        ThirdPhase
    }

    private GameGoal m_currentGoal = GameGoal.NoGoal;
    private GamePhase m_currentPhase = GamePhase.FirstPhase;

    //================================================================================================================================
    //================================================================================================================================
    public void SetCurrentGoal(GameGoal _goal) {
        m_currentGoal = _goal;
    }

    public GameGoal GetCurrentGoal() {
        return m_currentGoal;
    }

    //================================================================================================================================
    //================================================================================================================================
    public void SetCurrentPhase(GamePhase _phase) {
        m_currentPhase = _phase;
    }
    
    public GamePhase GetCurrentPhase() {
        return m_currentPhase;
    }
}
